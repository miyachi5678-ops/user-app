all_results = []

for seed, (ticker, name, start_price) in enumerate(NIKKEI225):
    df = make_sample_data(seed, start_price)
    result = run_backtest(df)

    if result.empty or len(result) < 5:
        continue

    total = len(result)
    wins = len(result[result["損益(%)"] > 0])
    win_rate = wins / total * 100
    avg_profit = result[result["損益(%)"] > 0]["損益(%)"].mean() if wins > 0 else 0
    avg_loss = result[result["損益(%)"] <= 0]["損益(%)"].mean() if (total - wins) > 0 else 0
    total_profit = result["損益(%)"].sum()
    stop_count = len(result[result["理由"] == "損切り"])

    all_results.append({
        "銘柄コード": ticker.replace(".T", ""),
        "銘柄名": name,
        "取引数": total,
        "勝率(%)": round(win_rate, 1),
        "平均利益(%)": round(avg_profit, 2),
        "平均損失(%)": round(avg_loss, 2),
        "累計損益(%)": round(total_profit, 2),
        "損切り回数": stop_count,
    })

