def check_signal(ticker):
    """買いシグナルが出ているか確認する。出ていれば株価情報を返す。"""
    try:
        raw = yf.download(ticker, period="60d", auto_adjust=True, progress=False)
        if raw.empty or len(raw) < MA_DAYS + 2:
            return None

        if isinstance(raw.columns, pd.MultiIndex):
            raw.columns = raw.columns.get_level_values(0)

        df = raw[["Close"]].copy()
        df.columns = ["close"]
        df["ma"] = df["close"].rolling(MA_DAYS).mean()
        df.dropna(inplace=True)

        if len(df) < 2:
            return None

        prev = df.iloc[-2]
        curr = df.iloc[-1]

        # 昨日は移動平均線以下、今日は以上 → 上抜けシグナル
        if prev["close"] < prev["ma"] and curr["close"] >= curr["ma"]:
            change_pct = (curr["close"] - prev["close"]) / prev["close"] * 100
            return {
                "price": round(float(curr["close"]), 0),
                "ma": round(float(curr["ma"]), 0),
                "change_pct": round(float(change_pct), 2),
            }
    except Exception:
        pass
    return None


def send_to_slack(message):
    payload = json.dumps({"text": message}).encode("utf-8")
    req = urllib.request.Request(
        SLACK_WEBHOOK_URL,
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req) as res:
        return res.read()


def main():
    today = date.today().strftime("%Y年%m月%d日")
    print(f"{today} 買いシグナルスキャン開始...")

    signals = []
    for ticker, name in NIKKEI225:
        result = check_signal(ticker)
        if result:
            signals.append((ticker, name, result))
            print(f"  シグナル検出: {name}（{ticker}）{result['price']}円")

    if not signals:
        message = f"*{today} 朝の買いシグナル通知*\n本日は買いシグナルが出た銘柄はありませんでした。"
    else:
        lines = [f"*{today} 朝の買いシグナル通知*", f"25日移動平均線を上抜けた銘柄が *{len(signals)}件* あります。\n"]
        for ticker, name, info in signals:
            code = ticker.replace(".T", "")
            sign = "+" if info["change_pct"] >= 0 else ""
            lines.append(
                f"• *{name}*（{code}）　{info['price']:,.0f}円　"
                f"MA25: {info['ma']:,.0f}円　前日比: {sign}{info['change_pct']}%"
            )
        message = "\n".join(lines)

    print("\nSlackに送信中...")
    send_to_slack(message)
    print("完了！")


if __name__ == "__main__":
    main()
